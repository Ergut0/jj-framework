const dictionaries: Record<string, Record<Key, string>> = { es, en };

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(locale: string): TFn {
  const dict = dictionaries[locale] ?? en;
  return (key, vars) => {
    const str = dict[key] ?? key;
    return vars ? str.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? "")) : str;
  };
}

/** Texto legible de una entrada de log/actividad */
export function formatLog(t: TFn, action: string, actor: string, details: Record<string, unknown>): string {
  const key = `log.${action}` as Key;
  const vars: Record<string, string | number> = { actor: actor || "system", reason: "" };
  for (const [k, v] of Object.entries(details ?? {})) {
    vars[k] = typeof v === "number" ? v.toLocaleString("es-ES") : String(v ?? "");
  }
  return key in es ? t(key, vars).trim() : action;
}

